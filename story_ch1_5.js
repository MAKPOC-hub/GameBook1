/* =========================================================================
   ГЛАВА 1. СУМРАЧНЫЙ БОР — часть 5
   Запуск игры.

   При загрузке страницы читаем сохранение. Если в нём остался незакрытый
   результат броска кубика (игрок обновил страницу, не нажав «Далее»),
   окно с тем же числом и последствиями покажется снова. Повторного
   броска не будет.
   ========================================================================= */

(function(){
  try{
    const raw=localStorage.getItem('zl_save');
    if(raw){
      const p=JSON.parse(raw);
      if(p&&p.node&&NODES[p.node]){
        S=p;
        hasSave=true;
      }
    }
  }catch(e){}
  if(!S)S=newState();
  render();
  /* ===== Восстановление отложенного окна броска кубика =====
     Окно результата сохраняется в состоянии игры до начала анимации.
     Если игрок обновит страницу — окно покажется снова с тем же числом,
     повторного броска не будет, обойти неудачу нельзя. */
  if(S&&S.pendingRoll&&typeof window._showRollOutcome==='function'){
    const pr=S.pendingRoll;
    window._showRollOutcome(pr.text,pr.nextNode,pr.outcome,pr.dice);
  }
  /* ===== Восстановление окна полученного стартового предмета =====
     Стартовый бросок на узле 3 тоже сохраняется заранее. Если игрок
     обновит страницу во время анимации — окно с полученным предметом
     покажется сразу. */
  if(S&&S.pendingStartItem){
    S.pendingStartItem=null;
    save();
    if(typeof showStartItemReceivedWindow==='function'){
      showStartItemReceivedWindow();
    }
  }
})();