/* ============================================================================
   ИНСТРУКЦИЯ ПО ЭТОМУ ФАЙЛУ
   ============================================================================

   ЧТО ЭТО ЗА ФАЙЛ.
   Здесь хранятся две вещи.

   Первая — версия игры. Одна строка. Эта версия показывается внизу справа
   на экране, чтобы её можно было быстро найти. Она же будет видна при
   проверке обновлений.

   Вторая — список последних изменённых файлов проекта с указанием
   их версий. Этот список игрок видит в игре — в окне настроек по кнопке
   «Инфо». Список нужен, чтобы можно было быстро проверить: применилось
   ли последнее изменение в проекте, или браузер отдаёт старую версию
   файла из кеша.

   ПРАВИЛО ПОВЫШЕНИЯ ВЕРСИИ ИГРЫ.
   Версия игры увеличивается на единицу при каждом изменении любого файла
   проекта. Например, если версия была 1.1.11, а в проект внесено хоть
   одно изменение в любом файле — версия игры становится 1.1.12.
   Следующее изменение — 1.1.13, и так далее.

   ПРАВИЛО ПОВЫШЕНИЯ ВЕРСИЙ ФАЙЛОВ.
   Каждый файл, который меняется, увеличивает свою версию на единицу.
   Версия файла хранится в шапке самого файла.

   ЧТО В НЕГО ЗАНОСИТЬ.
   При любом изменении проекта — поднять версию игры на единицу.
   При изменении любого файла проекта — добавить или обновить запись
   об этом файле в списке файлов. Запись в списке — одна строка,
   состоящая из имени файла и его текущей версии, разделённых пробелом.
   Пример обычной строки: 'style.css 2.6.10'

   ПОРЯДОК ЗАПИСЕЙ.
   Первая строка в списке файлов — самый свежий изменённый файл.
   Последняя строка — самый старый из списка.
   Всего в списке хранится десять записей. Когда добавляется новая,
   самая старая снизу удаляется, чтобы список оставался длиной десять.
   Файл, который уже есть в списке, не дублируется — вместо этого
   он передвигается наверх, и ему обновляется версия.

   ОБОЗНАЧЕНИЕ НОВЫХ ФАЙЛОВ.
   У новых записей — тех, что менялись в последнем обновлении, — в начале
   строки стоит обёртка «_ » (подчёркивание и пробел), а в конце — « _»
   (пробел и подчёркивание). У остальных записей обёртки нет.
   Пример новой записи: '_ style.css 2.6.13 _'
   Это визуально отделяет свежие изменения от давних. В окне «Инфо»
   новые записи видны с обёрткой — это и нужно.

   ЧТО НЕЛЬЗЯ ДЕЛАТЬ.
   Нельзя менять структуру списка файлов: это обычный список строк.
   Нельзя добавлять лишние знаки, скобки, дефисы, точки с запятой.
   Только имя файла, пробел и версия. Исключение — обёртка «_ » и « _»
   у новых записей.

   ============================================================================ */

